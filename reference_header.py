"""Эталонные заголовки SGO без контрольной суммы файла.

Вшиты в программу, чтобы версия определялась без образца на диске.
Разная прошивка — другой заголовок и другое смещение таблицы.
"""

from __future__ import annotations

from dataclasses import dataclass

from record_layout import CODING_FIELDS, Field, validate_fields


@dataclass(frozen=True)
class FirmwareProfile:
    name: str
    header: bytes
    table_start: int
    table_end: int
    fields: tuple[Field, ...] = CODING_FIELDS

    def __post_init__(self) -> None:
        validate_fields(self.fields)
        span = self.table_end - self.table_start + 1
        if span <= 0 or span % self.record_size:
            raise ValueError(
                f"Таблица {self.name} не делится на записи по {self.record_size} байт"
            )

    @property
    def record_size(self) -> int:
        return sum(field.size for field in self.fields)

    @property
    def record_count(self) -> int:
        return (self.table_end - self.table_start + 1) // self.record_size


