def match_firmware(header: bytes) -> FirmwareProfile | None:
    for profile in PROFILES:
        if profile.header == header:
            return profile
    return None


def supported_firmware_names() -> str:
    return "\n".join(f"• {profile.name}" for profile in PROFILES)
